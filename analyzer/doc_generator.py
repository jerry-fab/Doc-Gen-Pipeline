import os
from typing import List, Dict
from analyzer.models import ClassMetadata, ClassExplanation

class DocumentationGenerator:
    def __init__(self, output_dir: str = "docs"):
        self.output_dir = output_dir
        self.arch_dir = os.path.join(output_dir, "architecture")
        os.makedirs(self.arch_dir, exist_ok=True)

    def generate_class_doc(self, meta: ClassMetadata, explanation: ClassExplanation) -> str:
        lang_dir = os.path.join(self.arch_dir, meta.language.capitalize())
        os.makedirs(lang_dir, exist_ok=True)
        file_path = os.path.join(lang_dir, f"{meta.name}.md")

        mermaid = self._build_mermaid_diagram(meta)

        md = f"""# Class: `{meta.name}`

> **Language**: `{meta.language.upper()}` | **Source**: [`{meta.file_path}`](../../{meta.file_path}#L{meta.start_line}-L{meta.end_line}) | **Lines**: `{meta.start_line} - {meta.end_line}`

---

## 1. Class Architecture Diagram

```mermaid
{mermaid}
```

---

## 2. Overview & Purpose

{explanation.purpose}

### Why this class exists (Design Rationale)
{explanation.design_rationale}

---

## 3. Key Responsibilities

"""
        for resp in explanation.responsibilities:
            md += f"- {resp}\n"

        md += "\n---\n\n## 4. Method Signatures & Behavioral Analysis\n\n"
        md += "| Method Name | Parameters | Return Type | Lines | Explanation |\n"
        md += "| :--- | :--- | :--- | :--- | :--- |\n"
        for m in meta.methods:
            params_str = ", ".join(f"`{p.name}: {p.type_hint}`" for p in m.parameters) or "`none`"
            m_desc = explanation.key_methods_explained.get(m.name, m.docstring or "Executes method logic.")
            md += f"| **`{m.name}`** | {params_str} | `{m.return_type}` | L{m.start_line}-L{m.end_line} | {m_desc} |\n"

        if meta.dependencies:
            md += "\n---\n\n## 5. Injected Dependencies & Collaborators\n\n"
            for dep, role in explanation.dependencies_explained.items():
                md += f"- **`{dep}`**: {role}\n"

        md += "\n---\n\n## 6. Verifiable Code Citations\n\n"
        for citation in explanation.evidence_citations:
            md += f"- {citation}\n"

        md += "\n---\n\n## 7. Known Architectural Boundaries & Limitations\n\n"
        for lim in explanation.potential_limitations:
            md += f"- ⚠️ {lim}\n"

        md += "\n---\n*Auto-generated by GitHub Pipeline Code Documentation Engine.*\n"

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(md)

        return file_path

    def _build_mermaid_diagram(self, meta: ClassMetadata) -> str:
        lines = ["classDiagram"]
        # Class definition
        lines.append(f"    class {meta.name} {{")
        for f in meta.fields[:5]:
            clean_f = f.replace(";", "").replace("private", "-").replace("public", "+").replace("protected", "#")
            lines.append(f"        {clean_f}")
        for m in meta.methods:
            p_list = ", ".join(f"{p.type_hint} {p.name}" for p in m.parameters if p.name not in ('self', 'cls'))
            lines.append(f"        +{m.name}({p_list}) {m.return_type}")
        lines.append("    }")

        # Inheritance
        for base in meta.inherits:
            clean_base = base.replace("<", "~").replace(">", "~")
            lines.append(f"    {clean_base} <|-- {meta.name} : inherits")

        # Dependencies
        for dep in meta.dependencies:
            # extract type name if available
            dep_type = dep.split(":")[1].strip() if ":" in dep else dep.split()[0].strip()
            if dep_type and dep_type not in ("int", "str", "string", "bool", "double", "float"):
                clean_dep = dep_type.replace("<", "~").replace(">", "~")
                lines.append(f"    {meta.name} ..> {clean_dep} : depends on")

        return "\n".join(lines)

    def update_index(self, catalog: Dict[str, List[str]]):
        index_path = os.path.join(self.output_dir, "README.md")
        md = """# Automated Code Architecture & Class Catalog

This directory contains auto-generated architectural and functional documentation for all classes across the repository.

---

## Class Catalog by Language

"""
        for lang, class_files in sorted(catalog.items()):
            md += f"### {lang}\n\n"
            md += "| Class Name | Documentation Link |\n"
            md += "| :--- | :--- |\n"
            for c_path in sorted(class_files):
                c_name = os.path.splitext(os.path.basename(c_path))[0]
                rel_link = os.path.relpath(c_path, self.output_dir).replace("\\", "/")
                md += f"| **`{c_name}`** | [View Documentation]({rel_link}) |\n"
            md += "\n"

        md += "---\n*Updated automatically via GitHub CI/CD Pipeline.*\n"

        with open(index_path, "w", encoding="utf-8") as f:
            f.write(md)
